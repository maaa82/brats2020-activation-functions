def get_hero_slice(gt_vol, base_vol, win_vol, competitor_vols=None, threshold=0.7):
    """
    Finds a 2D slice where the winner outperforms the baseline AND top competitors on the NCR.
    """
    candidates = []

    for z in range(gt_vol.shape[0]):
        g = (gt_vol[z] == 1)
        if g.sum() == 0:
            continue

        p_win = (win_vol[z] == 1)
        p_base = (base_vol[z] == 1)

        # Calculate NCR Dice for Winner and Baseline
        d_win = (2*(p_win & g).sum()) / (p_win.sum() + g.sum() + 1e-5)
        d_base = (2*(p_base & g).sum()) / (p_base.sum() + g.sum() + 1e-5)

        # 1. Swish must be decent and beat the baseline
        if d_win > threshold and d_win > d_base:

            # 2. Check against competitors (if provided)
            beats_competitors = True
            if competitor_vols:
                for comp_vol in competitor_vols:
                    p_comp = (comp_vol[z] == 1)
                    d_comp = (2*(p_comp & g).sum()) / (p_comp.sum() + g.sum() + 1e-5)
                    # Require Swish to be strictly better than the competitor
                    if d_comp >= d_win:
                        beats_competitors = False
                        break

            # If it beats baseline AND all competitors, it's a candidate!
            if beats_competitors:
                candidates.append((g.sum(), d_win, d_base, z))

    if candidates:
        # Sort by size of the ground truth tumor (largest first)
        candidates.sort(key=lambda x: x[0], reverse=True)
        return candidates[0][3]

    # Fallback: If no perfect slice exists, return the one with the largest NCR ground truth
    print("⚠️ Could not find a perfect slice beating all competitors. Falling back to largest NCR slice.")
    return np.argmax(np.sum(gt_vol == 1, axis=(1, 2)))

