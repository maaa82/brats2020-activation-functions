def get_prediction(model, img_tensor, device):
    with torch.no_grad():
        input_tensor = img_tensor.unsqueeze(0).to(device)
        if torch.cuda.is_available():
            with torch.cuda.amp.autocast():
                pred = model(input_tensor)
        else:
            pred = model(input_tensor)
    return pred.argmax(dim=1).cpu().numpy()[0]

def calc_2d_dice(pred_slice, gt_slice, target_class=1):
    """Calculates Dice score for a specific class on a 2D slice."""
    p = (pred_slice == target_class)
    g = (gt_slice == target_class)
    intersection = (p & g).sum()
    union = p.sum() + g.sum()
    if union == 0:
        return 0.0
    return (2. * intersection) / union

